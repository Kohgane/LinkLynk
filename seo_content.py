def _faq_ld(pairs):
    import json
    d = {"@context": "https://schema.org", "@type": "FAQPage",
         "mainEntity": [{"@type": "Question", "name": q,
                         "acceptedAnswer": {"@type": "Answer", "text": a}}
                        for q, a in pairs]}
    return ('<script type="application/ld+json">%s</script>'
            % json.dumps(d, ensure_ascii=False))


